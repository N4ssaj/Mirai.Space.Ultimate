using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.Text;

namespace Mirai.Space.Extensions.Clone.SourceGeneration;

internal static class CloneEmitter
{
    private const string RuntimeNamespace = "global::Mirai.Space.Extensions.Clone";

    internal static void Emit(SourceProductionContext context, CloneCandidate candidate)
    {
        if (!candidate.IsEligible)
        {
            var descriptor = candidate.Diagnostic ?? CloneDiagnostics.Skipped;
            context.ReportDiagnostic(
                Diagnostic.Create(descriptor, Location.None, candidate.TypeDisplayName, candidate.SkipReason));
            return;
        }

        context.AddSource(candidate.HintName, SourceText.From(BuildPlan(candidate), Encoding.UTF8));

        if (!candidate.GenerateCloneMethod)
        {
            return;
        }

        if (!candidate.CanEmitMethods)
        {
            context.ReportDiagnostic(
                Diagnostic.Create(
                    CloneDiagnostics.MethodSkipped,
                    Location.None,
                    candidate.TypeDisplayName,
                    candidate.MethodSkipReason));
            return;
        }

        context.AddSource(
            candidate.ClassName + ".Methods.g.cs",
            SourceText.From(BuildMethods(candidate), Encoding.UTF8));
    }

    private static string BuildPlan(CloneCandidate candidate)
    {
        var builder = new StringBuilder();
        builder.AppendLine("// <auto-generated/>");
        builder.AppendLine("#nullable enable");
        builder.AppendLine();
        builder.AppendLine("namespace Mirai.Space.Extensions.Clone.Generated;");
        builder.AppendLine();
        builder.Append("internal static class ").Append(candidate.ClassName).AppendLine();
        builder.AppendLine("{");
        builder.AppendLine("    [global::System.Runtime.CompilerServices.ModuleInitializer]");
        builder.AppendLine("    internal static void Initialize()");
        builder.AppendLine("    {");
        builder.Append("        ").Append(RuntimeNamespace).Append(".CloneRegistry.Register<")
            .Append(candidate.TypeDisplayName).AppendLine(">(");
        builder.Append("            new ").Append(RuntimeNamespace).Append(".ClonePlan<")
            .Append(candidate.TypeDisplayName).AppendLine(">(");

        if (candidate.IsValueType)
        {
            builder.AppendLine("                static value => value,");
        }
        else
        {
            builder.Append("                static value => (").Append(candidate.TypeDisplayName)
                .Append(')').Append(RuntimeNamespace).AppendLine(".CloneRuntime.MemberwiseCloneObject(value),");
        }

        builder.AppendLine("                static (source, context) =>");
        builder.AppendLine("                {");
        if (!candidate.IsValueType)
        {
            builder.AppendLine("                    if (context.TryGetReference(source, out var existing))");
            builder.AppendLine("                    {");
            builder.Append("                        return (").Append(candidate.TypeDisplayName).AppendLine(")existing!;");
            builder.AppendLine("                    }");
            builder.AppendLine();
            builder.Append("                    var clone = (").Append(candidate.TypeDisplayName).Append(')')
                .Append(RuntimeNamespace).AppendLine(".CloneRuntime.MemberwiseCloneObject(source);");
            builder.AppendLine("                    context.RegisterReference(source, clone);");
        }
        else
        {
            builder.AppendLine("                    var clone = source;");
        }

        foreach (var member in candidate.Members)
        {
            var name = EscapeIdentifier(member.Name);
            builder.Append("                    clone.").Append(name)
                .Append(" = context.Clone(source.").Append(name).AppendLine(");");
        }

        builder.AppendLine("                    return clone;");
        builder.AppendLine("                }));");
        builder.AppendLine("    }");
        builder.AppendLine("}");
        return builder.ToString();
    }

    private static string BuildMethods(CloneCandidate candidate)
    {
        var builder = new StringBuilder();
        builder.AppendLine("// <auto-generated/>");
        builder.AppendLine("#nullable enable");
        if (candidate.Namespace is not null)
        {
            builder.AppendLine();
            builder.Append("namespace ").Append(candidate.Namespace).AppendLine(";");
        }

        builder.AppendLine();
        builder.Append(candidate.IsPublic ? "public " : "internal ");
        if (candidate.IsValueType && candidate.IsReadOnly)
        {
            builder.Append("readonly ");
        }

        builder.Append("partial ").Append(GetTypeKind(candidate)).Append(' ')
            .Append(EscapeIdentifier(candidate.DeclarationName)).AppendLine();
        builder.AppendLine("{");
        builder.Append("    public ").Append(candidate.TypeDisplayName).AppendLine(" Clone() =>");
        builder.Append("        ").Append(RuntimeNamespace).AppendLine(".Clone.Shallow(this);");
        builder.AppendLine();
        builder.Append("    public ").Append(candidate.TypeDisplayName).AppendLine(" DeepClone() =>");
        builder.Append("        ").Append(RuntimeNamespace).AppendLine(".Clone.Deep(this);");
        builder.AppendLine("}");
        return builder.ToString();
    }

    private static string GetTypeKind(CloneCandidate candidate)
    {
        if (candidate.IsRecord)
        {
            return candidate.IsValueType ? "record struct" : "record";
        }

        return candidate.IsValueType ? "struct" : "class";
    }

    private static string EscapeIdentifier(string name) =>
        SyntaxFacts.GetKeywordKind(name) != SyntaxKind.None
        || SyntaxFacts.GetContextualKeywordKind(name) != SyntaxKind.None
            ? "@" + name
            : name;
}
